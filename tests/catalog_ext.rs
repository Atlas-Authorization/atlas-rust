    c.app_catalog().presets(&q).await.unwrap();
    expected.push((
        HttpMethod::Get,
        "/v1/app_catalog?limit=2".into(),
        B::None,
        false,
    ));
    c.app_catalog().installed(&q).await.unwrap();
    expected.push((
        HttpMethod::Get,
        "/v1/app_catalog/installed?limit=2".into(),
        B::None,
        false,
    ));
    c.app_catalog()
        .install(
            "p0_id",
            &types_ext::AppCatalogInstallBody::default(),
            &q,
            Some("idem_1"),
        )
        .await
        .unwrap();
    expected.push((
        HttpMethod::Post,
        "/v1/app_catalog/p0_id/install?limit=2".into(),
        B::Obj,
        true,
    ));
    c.app_catalog()
        .update(
            "p0_id",
            &types_ext::AppCatalogUpdateBody::default(),
            &q,
            Some("idem_1"),
        )
        .await
        .unwrap();
    expected.push((
        HttpMethod::Patch,
        "/v1/app_catalog/installed/p0_id?limit=2".into(),
        B::Obj,
        true,
    ));
    c.app_catalog().uninstall("p0_id", &q).await.unwrap();
    expected.push((
        HttpMethod::Delete,
        "/v1/app_catalog/installed/p0_id?limit=2".into(),
        B::None,
        false,
    ));
